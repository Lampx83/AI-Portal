export type TeamKey = keyof typeof VI

/** t() cho tính năng nhóm: {name} được thay bằng tham số. */
export function useTeamText() {
  const { locale } = useLanguage()
  return useCallback(
    (key: TeamKey, params?: Record<string, string | number>) => {
      let s: string = locale === "vi" ? VI[key] : EN[key]
      if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v))
      return s
    },
    [locale]
  )
}

export function displayWho(email: string | null | undefined, names?: Map<string, string | null | undefined>): string {
  if (!email) return "—"
  return names?.get(email.toLowerCase()) || email.split("@")[0]
}
